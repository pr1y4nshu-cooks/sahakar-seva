import { Link, useParams } from 'react-router-dom';
import { useQuery } from '@tanstack/react-query';
import { ArrowLeft } from 'lucide-react';
import { Card } from '@/components/ui/Card';
import { Loading } from '@/components/ui/States';
import { Alert } from '@/components/marketplace/common';
import { TransactionTransparency } from '@/components/trust/TransactionTransparency';
import { errorMessage, timeRange } from '@/lib/marketplace';
import { downloadReceipt, publicApi, trust } from '@/lib/trust';

/** Signed-in view of one booking's evidence. Only a party to the booking can load it (server-enforced). */
export function BookingTransparency() {
  const { bookingId = '' } = useParams();
  const booking = useQuery({ queryKey: ['booking', bookingId], queryFn: () => publicApi.booking(bookingId), retry: false });
  const receipt = useQuery({ queryKey: ['receipt', bookingId], queryFn: () => trust.receipt(bookingId), retry: false });
  const b = booking.data;
  return (
    <div className="min-h-screen bg-cream px-4 py-10 lg:px-8">
      <div className="mx-auto max-w-4xl space-y-4">
        <Link to="/bookings" className="inline-flex items-center gap-1 text-sm font-semibold text-plum"><ArrowLeft size={14} aria-hidden="true" />My Bookings</Link>
        <h1 className="text-3xl font-black text-ink">Transaction transparency</h1>
        {b && (
          <p className="text-sm text-ink/70" data-testid="tt-booking">
            {b.skill.name} · {b.my_role === 'customer' ? `worker ${b.worker_display_name}` : `customer ${b.customer_display_name}`} · {timeRange(b.starts_at, b.ends_at)} · status <strong>{b.status}</strong>
            {b.is_synthetic_demo && <span className="ml-2 rounded-full bg-amber-100 px-2 py-0.5 text-xs font-semibold text-amber-900">Synthetic demo record</span>}
          </p>
        )}
        {(booking.isLoading || receipt.isLoading) && <Loading />}
        {(booking.isError || receipt.isError) && <Alert kind="error">{errorMessage(booking.error ?? receipt.error)}</Alert>}
        {b?.is_synthetic_demo && <Alert kind="info">This booking was generated by the demo seeder for a presentation. Its acceptances were recorded by a script on behalf of synthetic personas; no real person agreed to it and no real money moved.</Alert>}
        {receipt.data && <Card><TransactionTransparency receipt={receipt.data} service={b?.skill.name} onDownload={() => downloadReceipt(bookingId)} /></Card>}
      </div>
    </div>
  );
}
